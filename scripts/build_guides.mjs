function render(page, articles, site, preview, visible) {
  const { lang, country, title, slug } = page;
  const locale = locales[lang];
  const t = key => escape(shared.window.I18N.t(key, lang));
  const url = route(page);
  const href = target => path.posix.relative(path.posix.dirname(url), target);
  const home = preview ? base : href('index.html');
  const guideBase = new URL('guides/', base);
  function resolveLink(raw) {
    const target = URL.parse(raw, base + url);
    if (!target || !['http:', 'https:'].includes(target.protocol)) return null;
    if (target.origin === guideBase.origin && target.pathname.startsWith(guideBase.pathname)) {
      const pathname = target.pathname.replace(/\/$/, '/index.html');
      if (!visible.has(pathname)) return null;
      return href(pathname.slice(new URL(base).pathname.length)) + target.search + target.hash;
    }
    return target.href;
  }
  const peers = slug ? articles.filter(other => other.slug === slug) : lists.filter(other => other.country === country);
  const alternates = peers.length > 1 ? [...peers] : [];
  const chinese = alternates.find(other => other.lang === 'zh');
  const tags = alternates.map(other => [other.lang, route(other)]);
  if (chinese) tags.push(['x-default', route(chinese)]);
  const switcher = alternates.filter(other => other.lang !== lang).map(other =>
    `<a class="lang-btn" lang="${other.lang}" href="${href(route(other))}">${locales[other.lang].name}</a>`).join('');
  const listed = articles.filter(other => other.lang === lang && other.country === country);
  const description = page.description || (lang === 'zh' ? `查看${title}，了解当地天气与行李准备建议。` : `Explore ${title} for local weather and packing advice.`);
  const branded = escape(title + (lang === 'zh' ? '｜椰途' : ' | Yetu'));
  const artwork = covers.get(slug);
  const cover = artwork && 'guides/assets/' + artwork.file;
  if (cover && !fs.statSync(path.join(site, cover), { throwIfNoEntry: false })?.isFile()) {
    throw new Error('Missing guide cover: ' + cover);
  }
  const image = base + (cover || 'guides/assets/yetu-default.png');
  const org = { '@type': 'Organization', name: '椰途' };
  const schema = { '@context': 'https://schema.org', '@type': 'Article', headline: title, description,
    datePublished: page.date, image, inLanguage: lang, author: org, publisher: org };
  const figure = cover ? `<figure><img src="${href(cover)}" width="1200" height="630" alt="${escape(artwork[lang])}"><figcaption>${locale.credit}${artwork.date}</figcaption></figure>` : '';
  const entries = listed.map(other => `<li><time datetime="${other.date}">${other.date}</time>
  <h2><a href="${href(route(other))}">${escape(other.title)}</a></h2><p>${escape(other.description)}</p></li>`).join('\n');
  const content = slug ? `<article><a href="index.html">${locale.lists[country]}</a>
<h1>${escape(title)}</h1><time datetime="${page.date}">${page.date}</time>
${figure}
${markdown(page.body, title, resolveLink).replaceAll('<div class="guide-table"', `<p class="guide-swipe">${locale.swipe}</p><div class="guide-table"`)}</article>` : `<h1>${escape(title)}</h1>
${entries ? '<ul class="guide-list">' + entries + '</ul>' : '<p>' + locale.empty + '</p>'}`;
  return `${marker}
<html lang="${lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${branded}</title>
<meta name="description" content="${escape(description)}">
<link rel="canonical" href="${base + url}">
${tags.map(([code, target]) => `<link rel="alternate" hreflang="${code}" href="${base + target}">`).join('\n')}
<meta property="og:type" content="${slug ? 'article' : 'website'}">
<meta property="og:site_name" content="${t('app.title')}">
<meta property="og:title" content="${branded}">
<meta property="og:description" content="${escape(description)}">
<meta property="og:url" content="${base + url}">
<meta property="og:image" content="${image}">
<meta name="twitter:card" content="${cover ? 'summary_large_image' : 'summary'}">
<meta name="twitter:title" content="${branded}">
<meta name="twitter:description" content="${escape(description)}">
<meta name="twitter:image" content="${image}">
${preview ? '<meta name="robots" content="noindex,nofollow">' : ''}
${slug ? '<script type="application/ld+json">' + JSON.stringify(schema).replaceAll('<', '\\u003c') + '</script>' : ''}
<link rel="icon" href="${href('favicon.svg')}">
<link rel="stylesheet" href="${href('css/style.css')}">
<link rel="stylesheet" href="${href('css/guides.css')}">
</head>
<body>
<a class="skip-link" href="#main">${t('a11y.skipMain')}</a>
<header class="topbar"><div class="topbar-in">
<a class="brand" href="${home}?lang=${lang}"><span class="brand-logo">✈</span>
<span class="brand-txt"><span class="brand-title">${t('app.title')}</span><span class="brand-sub">${t('app.sub')}</span></span></a>
<div class="topbar-right">${switcher}</div></div></header>
<main id="main" class="guide-main panel" tabindex="-1">${content}</main>
<footer class="footer"><div class="panel">
<details class="footer-notes"><summary>${t('footer.disclaimerTitle')}</summary><p>${t('footer.disclaimer')}</p></details>
<details class="footer-method"><summary>${t('footer.sources')}</summary><p>${t('footer.method')}</p></details>
<div class="credit">${t('footer.credit')}</div></div></footer>
</body></html>
`;
}

export function buildGuides(site = root, { preview = false } = {}) {
  const articles = readGuides(site).filter(page => preview || !page.draft);
  const output = preview ? fs.mkdtempSync(path.join(os.tmpdir(), 'yetu-guides-')) : site;
  if (preview) {
    for (const asset of ['css', 'favicon.svg', 'guides/assets']) {
      fs.cpSync(path.join(site, asset), path.join(output, asset), { recursive: true });
    }
  }
  const pages = [...lists, ...articles];
  const generated = new Set(pages.map(route));
  const visible = new Set([...generated].map(url => new URL(url, base).pathname));
  for (const page of pages) {
    const target = path.join(output, route(page));
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, render(page, articles, site, preview, visible));
  }
  // A previously published slug can be renamed, removed or returned to draft.
  for (const list of lists) {
    const dir = path.dirname(route(list));
    for (const name of fs.readdirSync(path.join(output, dir))) {
      const relative = path.join(dir, name);
      if (!name.endsWith('.html') || generated.has(relative)) continue;
      const file = path.join(output, relative);
      if (fs.readFileSync(file, 'utf8').startsWith(marker)) fs.unlinkSync(file);
    }
  }
  if (!preview) writeSitemap(site);
  return output;
}

